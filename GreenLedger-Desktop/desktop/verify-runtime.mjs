import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import { FileBlob, SpreadsheetFile } from '@oai/artifact-tool';

const file = '../desktop-excel-qa/data/runtime-export.xlsx';
const book = await SpreadsheetFile.importXlsx(await FileBlob.load(file));
book.recalculate();
const summary = book.worksheets.getItem('Tong hop');
assert.ok(Math.abs(summary.getRange('G18').values[0][0] - 134.2818792) < 1e-8);
assert.ok(Math.abs(summary.getRange('G22').values[0][0] - 0.04216067896488621) < 1e-9);
book.worksheets.getItem('Hoat dong').getRange('E7').values = [[100000]];
book.recalculate();
assert.ok(Math.abs(summary.getRange('G18').values[0][0] - 268.5637584) < 1e-8);
book.worksheets.getItem('Hoat dong').getRange('E7').values = [[50000]];
book.recalculate();
for (const [name, range] of [['Tong hop', 'A1:H29'], ['Tinh toan', 'A7:G31'], ['Hoat dong', 'A5:H8'], ['He so', 'A15:H20']]) {
  const blob = await book.render({ sheetName: name, range, scale: 1.2, format: 'png' });
  await fs.writeFile('../excel-qa/Runtime-' + name + '.png', new Uint8Array(await blob.arrayBuffer()));
}
console.log('PASS: XLSX generated by desktop opens, formula results match, changing source recalculates linked totals.');
